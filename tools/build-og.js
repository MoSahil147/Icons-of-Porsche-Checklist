// Writes tools/og.html, the source of og-v3.png (1200 x 630): eight cars on an arc, one per paint,
// roofs out, with the event date at the hub. Run from the repo root, then screenshot:
//   bun tools/build-og.js
//   chromium --headless --hide-scrollbars --virtual-time-budget=5000 --window-size=1200,630 --screenshot=og-v3.png "file://$PWD/tools/og.html"
// Give the image a new name when the design changes: WhatsApp keeps a preview per image address for days.
const { readFileSync, writeFileSync } = require('node:fs');
const { paintedSVG } = require('../plan.js');

const car = readFileSync('sports-car.svg', 'utf8');
const tokens = readFileSync('tokens.css', 'utf8');
const paint = slug => tokens.match(new RegExp(`--paint-${slug}:\\s*(#[0-9a-f]{6})`, 'i'))[1];
// Same order as the paint picker. The convoy runs clockwise, so Guards Red leads at the right end.
const PAINTS = ['guards-red', 'racing-yellow', 'irish-green', 'miami-blue', 'lava-orange', 'chalk', 'carrara-white', 'carmine-red'];
const [svgW, svgH] = car.match(/viewBox="0 0 (\d+) (\d+)"/).slice(1).map(Number);

const cx = 600, cy = 640, radius = 500, width = 186, height = width * svgH / svgW;
const cars = PAINTS.map((slug, k) => {
  const angle = (14 + k * 152 / 7) * Math.PI / 180;
  const x = cx + radius * Math.cos(angle), y = cy - radius * Math.sin(angle);
  const src = 'data:image/svg+xml,' + encodeURIComponent(paintedSVG(car, paint(slug)));
  return `<img src="${src}" alt="" style="left:${(x - width / 2).toFixed(0)}px;top:${(y - height / 2).toFixed(0)}px;width:${width}px;transform:rotate(${(90 - angle * 180 / Math.PI).toFixed(1)}deg)">`;
}).join('\n');

writeFileSync('tools/og.html', `<!DOCTYPE html>
<!-- Generated by tools/build-og.js. Do not edit by hand. -->
<html lang="en-GB">
<head>
<meta charset="utf-8">
<title>og image</title>
<link rel="stylesheet" href="../tokens.css">
<style>
html, body { margin: 0; width: 1200px; height: 630px; overflow: hidden; background: var(--color-paper); color: var(--color-ink); }
.card { position: relative; width: 1200px; height: 630px; }
img { position: absolute; transform-origin: 50% 50%; }
.hub { position: absolute; left: 0; right: 0; top: 300px; text-align: center; }
h1 { margin: 0; font: 800 50px/1 var(--font-display); letter-spacing: -0.03em; }
.date { margin: 22px 0 0; font: 800 104px/0.9 var(--font-display); letter-spacing: -0.04em; color: var(--color-accent); }
.where { margin: 10px 0 0; font: 600 22px/1.2 var(--font-body); color: var(--color-ink-2); }
</style>
</head>
<body><div class="card">
${cars}
<div class="hub"><h1>Every tick builds your 911.</h1><p class="date">21 + 22 Nov</p><p class="where">Icons of Porsche, Dubai. A fan-made guide.</p></div>
</div></body>
</html>
`);
console.log('wrote tools/og.html');
